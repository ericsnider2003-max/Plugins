#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { canAdmit } from "../scripts/admission.mjs";
import { writeNotice } from "../scripts/notifications.mjs";
const task = { taskId: "task-admission-001" };
const base = { state: "governing", authority: "provider", freshness: "fresh", capturedAt: "2026-10-15T08:00:00Z", model: { known: true, canonical: "gpt-5.6-luna" }, window: { usedPercentage: 40 } };
const now = Date.parse("2026-10-15T08:05:00Z");
assert.equal(canAdmit({ task, observation: base, accountApproved: true, now }).allowed, true);
assert.equal(canAdmit({ task, observation: { ...base, authority: "local-activity" }, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task, observation: { ...base, state: "quarantined" }, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task, observation: { ...base, state: "observing" }, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task, observation: { ...base, freshness: "stale" }, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task, observation: base, accountApproved: false, now }).allowed, false);
assert.equal(canAdmit({ task, observation: { ...base, capturedAt: "2026-10-15T07:00:00Z" }, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task, observation: { ...base, window: { usedPercentage: 95 } }, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task, observation: { ...base, model: null }, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task, observation: { ...base, model: null }, accountApproved: true, now, requireKnownModel: false }).allowed, true);
assert.equal(canAdmit({ task: { ...task, requestedModel: "gpt-5.6-sol" }, observation: base, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task: { ...task, requestedEffort: "high" }, observation: { ...base, model: { ...base.model, effort: "medium" } }, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task: { ...task, deadlineAt: "2026-10-15T08:04:00Z" }, observation: base, accountApproved: true, now }).allowed, false);
assert.equal(canAdmit({ task: { ...task, maxConcurrency: 1 }, observation: base, accountApproved: true, now, activeTaskCount: 1 }).allowed, false);
assert.equal(canAdmit({ task, observation: { ...base, model: { ...base.model, raw: "claude-sonnet-5-5", provider: "unknown" } }, accountApproved: true, now }).allowed, false);
const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "usage-max-notice-")), "outbox.jsonl");
const notice = { noticeId: "notice-001", kind: "usage-paused", message: "Task paused because verified capacity is unavailable." };
assert.equal(writeNotice(file, notice).written, true); assert.equal(writeNotice(file, notice).duplicate, true);
console.log("admission and notification tests passed");
